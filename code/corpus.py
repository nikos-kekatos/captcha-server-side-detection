"""Corpus counts -> ../generated.tex (LaTeX macros) and ../figures/corpus_eras.pdf.
Never edit generated.tex by hand; rerun this script after changing lit/corpus.csv."""
from __future__ import annotations

import csv
from collections import Counter
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from plots import C, COL, INK, MUTED  # shared style

ROOT = Path(__file__).resolve().parent.parent
rows = list(csv.DictReader(open(ROOT / "lit" / "corpus.csv")))
ERAS = [("$\\leq$2009", 0, 2009), ("2010–14", 2010, 2014), ("2015–19", 2015, 2019),
        ("2020–22", 2020, 2022), ("2023–26", 2023, 2026)]
FAM = {  # coded ai_family -> plotted group (fixed order = fixed colour)
    "segmentation+classifier": "segmentation + classical ML",
    "other": "segmentation + classical ML",
    "CNN": "CNN / CRNN / transformer",
    "CNN-CTC/CRNN": "CNN / CRNN / transformer",
    "transformer": "CNN / CRNN / transformer",
    "GAN": "GAN / generative",
    "generative-model": "GAN / generative",
    "ASR": "speech recognition",
    "object-detection": "object detection",
    "RL/agent": "RL / agent",
    "VLM/LLM": "LLM / VLM",
}
GROUPS = ["segmentation + classical ML", "CNN / CRNN / transformer", "GAN / generative",
          "speech recognition", "object detection", "RL / agent", "LLM / VLM"]


def era(y):
    y = int(y)
    for i, (_, a, b) in enumerate(ERAS):
        if a <= y <= b:
            return i


def main():
    n = len(rows)
    att = [r for r in rows if r["role"] == "attack"]
    M = np.zeros((len(GROUPS), len(ERAS)))
    for r in att:
        g = FAM.get(r["ai_family"])
        if g:
            M[GROUPS.index(g), era(r["year"])] += 1
    fig, ax = plt.subplots(figsize=(COL, 1.3))
    ax.grid(axis="x", visible=False)
    bottom = np.zeros(len(ERAS))
    for i, g in enumerate(GROUPS):
        ax.bar(range(len(ERAS)), M[i], bottom=bottom, color=C[i], width=0.62, label=g,
               edgecolor="white", linewidth=1.0)
        bottom += M[i]
    for j, b in enumerate(bottom):
        ax.text(j, b + 0.4, f"{int(b)}", ha="center", fontsize=6.5, color=INK)
    ax.set_xticks(range(len(ERAS)), [e[0] for e in ERAS])
    ax.set_ylabel("attack works")
    ax.set_ylim(0, bottom.max() * 1.15)
    ax.legend(fontsize=5.4, loc="upper left", ncol=1)
    fig.tight_layout(pad=0.2)
    fig.savefig(ROOT / "figures" / "corpus_eras.pdf")

    role = Counter(r["role"] for r in rows)
    typ = Counter(r["captcha_type"] for r in rows)
    fam = Counter(r["ai_family"] for r in rows)
    recent = [r for r in rows if int(r["year"]) >= 2023]
    llm_recent = sum(1 for r in recent if r["ai_family"] == "VLM/LLM")
    mac = {
        "CorpusN": n, "CorpusAttack": role["attack"], "CorpusDefence": role["defence"],
        "CorpusMeasure": role["measurement"], "CorpusSurvey": role["survey"],
        "CorpusEcon": role["economics"], "CorpusText": typ["text"], "CorpusAudio": typ["audio"],
        "CorpusImage": typ["image"], "CorpusBehav": typ["behavioural"], "CorpusToken": typ["pow_token"],
        "CorpusCognitive": typ["cognitive"], "CorpusGeneral": typ["general"],
        "CorpusGame": typ["game"], "CorpusSlider": typ["slider"],
        "CorpusRecent": len(recent), "CorpusLLM": fam["VLM/LLM"], "CorpusLLMRecent": llm_recent,
        "CorpusAdv": fam["adversarial-examples"],
        "CorpusAttRecent": int(M[:, -1].sum()), "CorpusAttLLMRecent": int(M[GROUPS.index("LLM / VLM"), -1]),
    }
    out = ["% generated by code/corpus.py from lit/corpus.csv; do not edit"]
    out += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in mac.items()]
    (ROOT / "generated.tex").write_text("\n".join(out) + "\n")
    print(mac)


if __name__ == "__main__":
    main()
