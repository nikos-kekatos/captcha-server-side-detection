def pct(x, d=1):
    return f"{100 * x:.{d}f}"


def put(k, v, note):
    mac[k] = str(v)
    md.append(f"- `\\{k}` = {v}  ({note})")


def wilson(k, n, z=1.96):
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0, c - h), min(1, c + h)


