"""Macros and the rate-bound table for the 2026-10-27 review runs (code/review1027.py).

Reads results/review1027_A2.json, review1027_C.json, review1027_D.json, e5.json (gap_sensitivity)
and the IP prices of results.tex. Writes ../generated_review1027.tex and ../tab_gap.tex.
Never edit the outputs by hand.
"""
import json
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
out = []


def put(name, val, src):
    out.append(f"\\newcommand{{\\{name}}}{{{val}}} % {src}")


def pct(x, d=1):
    return f"{100 * x:.{d}f}"


# A2: realised 1% operating point of P1-P6
a2 = json.loads((R / "review1027_A2.json").read_text())["A2"]
budgets = sorted({x["budget"] for x in a2})
rate = {(x["budget"], x["profile"]): x["rate"] for x in a2}
ok = [b for b in budgets if rate[(b, "Human, held-out")] <= 0.01]
b = max(ok) if ok else min(budgets)
put("RealBudget", f"{100 * b:.2g}", "A2 nominal budget (%) with realised held-out rate <= 1%")
for key, prof in [("Hum", "Human, held-out"), ("Pool", "Pooled mimic, full accuracy"),
                  ("Farm", "Farm relay, human gap"), ("Delay", "Fixed delay, human gap"),
                  ("Crnn", "CRNN, direct"), ("Qwen", "VLM qwen3.5_9b, direct"),
                  ("Pers", "Person mimic, full accuracy")]:
    put("Real" + key, pct(rate[(b, prof)]), f"A2 budget {b}: {prof}")
put("RealCalStreams", "20,000", "A2 calibration streams")

# C: telemetry faults
c = json.loads((R / "review1027_C.json").read_text())["C"]
cr = {(x["variant"], x["fault"], x["profile"]): x["rate"] for x in c}
for v, tag in (("P1-P6", "Six"), ("P1-P5", "Five")):
    for f, ftag in (("none", "None"), ("missing", "Miss"), ("delay", "Delay"), ("shared2", "ShTwo"), ("shared5", "ShFive")):
        put(f"Flt{ftag}Hum{tag}", pct(cr[(v, f, "Human, held-out")]), f"C {v} {f} human")
    for f, ftag in (("none", "None"), ("missing", "Miss"), ("delay", "Delay")):
        put(f"Flt{ftag}Pool{tag}", pct(cr[(v, f, "Pooled mimic, full accuracy")]), f"C {v} {f} pooled mimic")
        put(f"Flt{ftag}Crnn{tag}", pct(cr[(v, f, "CRNN, direct")], 0), f"C {v} {f} CRNN direct")

# D: total-variation lower bounds per statistic
d = json.loads((R / "review1027_D.json").read_text())["D"]
noise = max(d["Human (second sample)"].values())
put("TvNoise", f"{noise:.2f}", "D max TV between two human samples (estimation noise floor)")
ph = d["Person mimic, human accuracy"]
put("TvPersHum", f"{max(ph.values()):.2f}", "D person mimic human accuracy, max TV over statistics")
put("TvPersFullAcc", f"{d['Person mimic, full accuracy']['correct']:.2f}", "D person mimic full accuracy, TV of correct count")
pf = {k: v for k, v in d["Person mimic, full accuracy"].items() if k != "correct"}
put("TvPersFullLat", f"{max(pf.values()):.2f}", "D person mimic full accuracy, max TV over latency/rate statistics")
put("TvPoolSd", f"{d['Pooled mimic, full accuracy']['sd_log_latency']:.2f}", "D pooled mimic, TV of SD log latency")
put("TvFarmSd", f"{d['Farm relay, human gap']['sd_log_latency']:.2f}", "D farm relay human gap, TV of SD log latency")
put("TvDelayCv", f"{d['Fixed delay, human gap']['min_cv']:.2f}", "D fixed delay human gap, TV of min CV")
put("TvDelaySd", f"{d['Fixed delay, human gap']['sd_log_latency']:.2f}", "D fixed delay human gap, TV of SD log latency")

# rate-bound sensitivity table (e5.json gap_sensitivity) with IP prices from results.tex
e5 = json.loads((R / "e5.json").read_text())
res = (ROOT / "results.tex").read_text()
ip_lo = float(re.search(r"\\newcommand\{\\MktIpLo\}\{([\d.]+)\}", res).group(1))
ip_hi = float(re.search(r"\\newcommand\{\\MktIpHi\}\{([\d.]+)\}", res).group(1))
rows = []
for g in e5["gap_sensitivity"]:
    keys = math.ceil(1e6 / (24 * g["bound"]))
    gap = f"{g['gap_s'] / 60:.0f}\\,min" if g["gap_s"] >= 60 else f"{g['gap_s']:.0f}\\,s"
    rows.append(f"{gap} & {g['k4']} & {g['bound']:.1f} & {keys:,} & {keys * ip_lo / 30:,.0f}--{keys * ip_hi / 30:,.0f} \\\\")
gk = {g["gap_s"]: math.ceil(1e6 / (24 * g["bound"])) for g in e5["gap_sensitivity"]}
put("GapKeysOneMin", f"{gk[60.0]:,}", "keys for 1M/day at a 1-min human gap")
put("GapKFourThirtyMin", str([g["k4"] for g in e5["gap_sensitivity"] if g["gap_s"] == 1800.0][0]), "k4 at a 30-min human gap")
put("GapKeysThirtyMin", f"{gk[1800.0]:,}", "keys for 1M/day at a 30-min human gap")
(ROOT / "tab_gap.tex").write_text(
    "% generated by code/macros_review1027.py from results/e5.json (gap_sensitivity) and the IP prices of results.tex\n"
    "\\begin{tabular}{@{}rrrrr@{}}\n\\toprule\n"
    "\\textbf{Mean gap} & $\\boldsymbol{k_4}$ & \\textbf{Solves/h} & \\textbf{Keys} & \\textbf{IP USD/day} \\\\\n\\midrule\n"
    + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
(ROOT / "generated_review1027.tex").write_text(
    "% generated by code/macros_review1027.py; do not edit\n" + "\n".join(out) + "\n")
print("\n".join(out))
print("\n".join(rows))
